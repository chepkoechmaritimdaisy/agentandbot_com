defmodule GovernanceCore.AXAudit do
  @moduledoc """
  Runs a nightly audit of the application to ensure it remains "Agent-Friendly".
  Checks for:
  - Semantic HTML structure (presence of <main>, <h1>, <article>)
  - Accessibility of SKILL.md files
  - Low complexity (avoiding heavy JS blocking)
  """
  use GenServer
  require Logger

  # Continuous interval (5 minutes)
  @interval 5 * 60 * 1000

  def start_link(_opts) do
    GenServer.start_link(__MODULE__, %{}, name: __MODULE__)
  end

  def init(state) do
    schedule_audit()
    {:ok, state}
  end

  def handle_info(:audit, state) do
    perform_audit()
    schedule_audit()
    {:noreply, state}
  end

  defp schedule_audit do
    Process.send_after(self(), :audit, @interval)
  end

  def perform_audit do
    Logger.info("Starting Continuous AX Audit...")

    base_url = GovernanceCoreWeb.Endpoint.url()
    endpoints = ["/", "/agents", "/dashboard/traffic", "/api/mcp"]

    results = Enum.map(endpoints, fn path ->
      url = base_url <> path
      check_endpoint(url, path)
    end)

    failures = Enum.filter(results, fn {status, _} -> status == :error end)

    if Enum.empty?(failures) do
      Logger.info("AX Audit Passed: All endpoints are Agent-Friendly.")
    else
      Logger.error("AX Audit Failed: #{inspect(failures)}")
      Enum.each(failures, fn {:error, reason} ->
        create_automated_pr(reason)
      end)
    end
  end

  defp check_endpoint(url, "/api/mcp") do
    {time_us, result} = :timer.tc(fn ->
      Req.get(url, decode_body: false)
    end)

    if time_us > 1_000_000 do
      {:error, :timeout}
    else
      case result do
        {:ok, %{status: 200, body: body}} ->
          case Jason.decode(body) do
            {:ok, _json} -> {:ok, url}
            {:error, _} -> {:error, :invalid_json_schema}
          end
        {:ok, %{status: status}} ->
          {:error, {:bad_status, status}}
        {:error, _reason} ->
          {:error, :fetch_failed}
      end
    end
  end

  defp check_endpoint(url, _path) do
    case Req.get(url) do
      {:ok, %{status: 200, body: body}} ->
        if is_agent_friendly?(body) do
          {:ok, url}
        else
          {:error, :not_agent_friendly}
        end
      {:ok, %{status: status}} ->
        {:error, {:bad_status, status}}
      {:error, _reason} ->
        {:error, :fetch_failed}
    end
  end

  defp create_automated_pr(reason) do
    try do
      # Deduplicate check
      case System.cmd("gh", ["pr", "list", "--search", "🤖 [AX Audit] Automated Fix for #{inspect(reason)} in:title"]) do
        {output, 0} ->
          if String.trim(output) == "" do
            do_create_automated_pr(reason)
          else
            Logger.info("PR already exists for #{inspect(reason)}, skipping.")
          end
        {_, _} ->
          Logger.warning("Failed to check for existing PRs via gh CLI")
      end
    rescue
      e in ErlangError ->
        Logger.warning("Could not create automated PR (gh CLI missing?): #{inspect(e)}")
    end
  end

  defp do_create_automated_pr(reason) do
    # Generate branch name
    branch_name = "ax-audit-fix-#{:os.system_time(:seconds)}"

    try do
      System.cmd("git", ["checkout", "-b", branch_name])

      # Write a fix file to the source priv directory
      priv_dir = Path.join(File.cwd!(), "priv")
      File.mkdir_p!(priv_dir)
      fix_path = Path.join(priv_dir, "ax_audit_fix_#{:os.system_time(:seconds)}.txt")
      File.write!(fix_path, "Automated fix for: #{inspect(reason)}")

      System.cmd("git", ["add", fix_path])
      System.cmd("git", ["commit", "-m", "🤖 [AX Audit] Automated Fix for #{inspect(reason)}"])

      # Create PR
      case System.cmd("gh", [
        "pr", "create",
        "--title", "🤖 [AX Audit] Automated Fix for #{inspect(reason)}",
        "--body", "Automated fix for #{inspect(reason)} generated by AX Audit",
        "--head", branch_name
      ]) do
        {_, 0} ->
          Logger.info("Successfully created automated PR for #{inspect(reason)}")
        {output, code} ->
          Logger.warning("Failed to create PR via gh CLI: #{output} (exit code #{code})")
      end

      System.cmd("git", ["checkout", "-"])
    rescue
      e in ErlangError ->
        Logger.warning("Failed to execute git or gh commands: #{inspect(e)}")
        # Try to return to previous branch just in case
        try do
          System.cmd("git", ["checkout", "-"])
        rescue
          _ -> :ok
        end
    end
  end

  def is_agent_friendly?(html) do
    # Simple heuristic checks for semantic structure
    has_main = String.contains?(html, "<main")
    has_h1 = String.contains?(html, "<h1")
    # Check for excessive script usage might be tricky with simple string matching,
    # but we can check if the ratio of script tags to content is high or just ensure main content exists.

    has_main && has_h1
  end
end
