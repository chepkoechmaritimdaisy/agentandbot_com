defmodule GovernanceCore.AXAudit do
  @moduledoc """
  Runs a nightly audit of the application to ensure it remains "Agent-Friendly".
  Checks for:
  - Semantic HTML structure (presence of <main>, <h1>, <article>)
  - Accessibility of SKILL.md files
  - Low complexity (avoiding heavy JS blocking)
  """
  use GenServer
  require Logger

  # 24 hours in milliseconds for legacy audit
  @audit_interval 24 * 60 * 60 * 1000
  # 1 minute for continuous MCP audit
  @mcp_interval 60 * 1000

  def start_link(_opts) do
    GenServer.start_link(__MODULE__, %{}, name: __MODULE__)
  end

  def init(state) do
    schedule_audit()
    schedule_mcp_audit()
    {:ok, state}
  end

  def handle_info(:audit, state) do
    perform_audit()
    schedule_audit()
    {:noreply, state}
  end

  def handle_info(:mcp_audit, state) do
    perform_mcp_audit()
    schedule_mcp_audit()
    {:noreply, state}
  end

  defp schedule_audit do
    Process.send_after(self(), :audit, @audit_interval)
  end

  defp schedule_mcp_audit do
    Process.send_after(self(), :mcp_audit, @mcp_interval)
  end

  def perform_audit do
    Logger.info("Starting Nightly AX Audit...")

    base_url = GovernanceCoreWeb.Endpoint.url()
    endpoints = ["/", "/agents", "/dashboard/traffic"]

    results = Enum.map(endpoints, fn path ->
      url = base_url <> path
      check_endpoint(url)
    end)

    failures = Enum.filter(results, fn {status, _} -> status == :error end)

    if Enum.empty?(failures) do
      Logger.info("AX Audit Passed: All endpoints are Agent-Friendly.")
    else
      Logger.error("AX Audit Failed: #{inspect(failures)}")
    end
  end

  def perform_mcp_audit do
    Logger.info("Starting Continuous MCP Audit...")
    base_url = GovernanceCoreWeb.Endpoint.url()

    case check_mcp_endpoint(base_url <> "/api/mcp") do
      {:ok, _} ->
        Logger.info("MCP Endpoint is healthy.")
      {:error, reason} ->
        Logger.error("MCP Audit Failed: #{reason}")
        create_automated_pr([{:error, reason}])
    end
  end

  defp check_endpoint(url) do
    case Req.get(url) do
      {:ok, %{status: 200, body: body}} ->
        if is_agent_friendly?(body) do
          {:ok, url}
        else
          {:error, "Endpoint #{url} is not agent-friendly (missing semantic tags or too complex)"}
        end
      {:ok, %{status: status}} ->
        {:error, "Endpoint #{url} returned status #{status}"}
      {:error, reason} ->
        {:error, "Failed to fetch #{url}: #{inspect(reason)}"}
    end
  end

  defp check_mcp_endpoint(url) do
    {time, result} = :timer.tc(fn -> Req.get(url, decode_body: false) end)
    # Convert microseconds to milliseconds
    time_ms = time / 1000

    if time_ms > 1000 do
      {:error, "Endpoint #{url} response time exceeded 1000ms"}
    else
      case result do
        {:ok, %{status: 200, body: body}} ->
          case Jason.decode(body) do
            {:ok, _json} -> {:ok, url}
            {:error, _} -> {:error, "Endpoint #{url} returned invalid JSON schema"}
          end
        {:ok, %{status: status}} ->
          {:error, "Endpoint #{url} returned status #{status}"}
        {:error, reason} ->
          {:error, "Failed to fetch #{url}: #{inspect(reason)}"}
      end
    end
  end

  defp create_automated_pr(failures) do
    try do
      # Search for existing PRs to prevent spam loops
      search_cmd = "gh pr list --search '🤖 [AX Audit] Automated Fix in:title' --state open"
      case System.cmd("bash", ["-c", search_cmd]) do
        {output, 0} ->
          if String.trim(output) == "" do
            do_create_pr(failures)
          else
            Logger.info("Automated PR already exists. Skipping PR creation.")
          end
        {err, _} ->
          Logger.error("Failed to check for existing PRs: #{inspect(err)}")
      end
    rescue
      e -> Logger.error("Error creating automated PR: #{inspect(e)}")
    end
  end

  defp do_create_pr(failures) do
    branch_name = "ax-audit-fix-#{System.system_time(:second)}"

    # We serialize the errors to valid JSON string map list, but since failures are simple tuples,
    # we can just write a text log file for simplicity, or format it as string.
    formatted_failures = Enum.map(failures, fn {:error, reason} -> reason end) |> Enum.join("\n")

    # We modify a file in priv/ to not break git
    fix_file_path = Path.join(File.cwd!(), "priv/ax_audit_report.txt")
    File.write!(fix_file_path, "AX Audit Failures:\n#{formatted_failures}\n")

    System.cmd("git", ["checkout", "-b", branch_name])
    System.cmd("git", ["add", "priv/ax_audit_report.txt"])
    System.cmd("git", ["commit", "-m", "🤖 [AX Audit] Automated Fix\n\nGenerated by continuous AX audit."])
    System.cmd("git", ["push", "-u", "origin", branch_name])

    case System.cmd("gh", ["pr", "create", "--title", "🤖 [AX Audit] Automated Fix", "--body", "Automated fix for AX audit failures."]) do
      {_, 0} -> Logger.info("Successfully created automated PR.")
      {err, _} -> Logger.error("Failed to create automated PR: #{inspect(err)}")
    end

    System.cmd("git", ["checkout", "-"])
  end

  defp is_agent_friendly?(html) do
    # Simple heuristic checks for semantic structure
    has_main = String.contains?(html, "<main")
    has_h1 = String.contains?(html, "<h1")
    # Check for excessive script usage might be tricky with simple string matching,
    # but we can check if the ratio of script tags to content is high or just ensure main content exists.

    has_main && has_h1
  end
end
