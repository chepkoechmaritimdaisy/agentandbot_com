defmodule GovernanceCore.AXAudit do
  @moduledoc """
  Runs a nightly audit of the application to ensure it remains "Agent-Friendly".
  Checks for:
  - Semantic HTML structure (presence of <main>, <h1>, <article>)
  - Accessibility of SKILL.md files
  - Low complexity (avoiding heavy JS blocking)
  """
  use GenServer
  require Logger

  # 24 hours in milliseconds
  @interval 24 * 60 * 60 * 1000
  # 1 minute in milliseconds
  @continuous_interval 60 * 1000

  def start_link(_opts) do
    GenServer.start_link(__MODULE__, %{}, name: __MODULE__)
  end

  def init(state) do
    schedule_audit()
    schedule_continuous_audit()
    {:ok, state}
  end

  def handle_info(:audit, state) do
    perform_audit()
    schedule_audit()
    {:noreply, state}
  end

  def handle_info(:continuous_audit, state) do
    perform_continuous_audit()
    schedule_continuous_audit()
    {:noreply, state}
  end

  defp schedule_audit do
    Process.send_after(self(), :audit, @interval)
  end

  defp schedule_continuous_audit do
    Process.send_after(self(), :continuous_audit, @continuous_interval)
  end

  def perform_audit do
    Logger.info("Starting Continuous AX Audit...")

    base_url = GovernanceCoreWeb.Endpoint.url()
    endpoints = ["/", "/agents", "/dashboard/traffic"]

    results = Enum.map(endpoints, fn path ->
      url = base_url <> path
      check_endpoint(url)
    end)

    failures = Enum.filter(results, fn {status, _} -> status == :error end)

    if Enum.empty?(failures) do
      Logger.info("AX Audit Passed: All endpoints are Agent-Friendly.")
    else
      Logger.error("AX Audit Failed: #{inspect(failures)}")
    end
  end

  def perform_continuous_audit do
    Logger.debug("Running Continuous MCP Audit...")
    base_url = GovernanceCoreWeb.Endpoint.url()
    url = base_url <> "/api/mcp"

    start_time = System.monotonic_time(:millisecond)

    case Req.get(url) do
      {:ok, %{status: status, body: body}} when status in 200..299 ->
        end_time = System.monotonic_time(:millisecond)
        duration = end_time - start_time

        is_json = is_map(body) or is_list(body)

        if duration > 1000 or not is_json do
           Logger.error("MCP Audit Failed: duration: #{duration}ms, is_json: #{is_json}")
           create_fix_pr(duration, is_json)
        else
           Logger.debug("MCP Audit Passed: duration: #{duration}ms")
        end
      {:ok, %{status: status}} ->
         Logger.error("MCP Audit Failed: HTTP Status #{status}")
         create_fix_pr("HTTP Error", status)
      {:error, reason} ->
         Logger.error("MCP Audit Failed: #{inspect(reason)}")
         create_fix_pr("Request Failed", inspect(reason))
    end
  end

  defp create_fix_pr(reason, context) do
    Logger.info("Creating Fix PR for MCP Audit Failure...")
    branch_name = "fix-mcp-audit-#{System.unique_integer([:positive])}"

    # Check for existing open PRs to prevent spam loop
    try do
      case System.cmd("gh", ["pr", "list", "--search", "fix-mcp-audit", "--state", "open"]) do
        {output, 0} ->
           if String.trim(output) == "" do
               perform_pr_creation(branch_name, reason, context)
           else
               Logger.info("A fix PR is already open. Skipping creation.")
           end
        {err, _code} ->
           Logger.error("Failed to check existing PRs: #{err}")
      end
    rescue
      e in ErlangError ->
        Logger.error("Failed to execute gh CLI. Ensure it is installed. Error: #{inspect(e)}")
    end
  end

  defp perform_pr_creation(branch_name, reason, context) do
      try do
          # Create and checkout a unique branch
          System.cmd("git", ["checkout", "-b", branch_name])

          # Modify a file to trigger a commit (in the source tree, e.g., priv/mcp_audit_fix.log)
          fix_file_path = Path.join(File.cwd!(), "priv/mcp_audit_fix.log")
          File.write!(fix_file_path, "Auto-generated fix log.\\nReason: #{inspect(reason)}\\nContext: #{inspect(context)}\\n")

          # Stage and commit
          System.cmd("git", ["add", fix_file_path])
          System.cmd("git", ["commit", "-m", "Automated fix for MCP endpoint issue"])

          # Create PR using gh CLI
          System.cmd("gh", ["pr", "create", "--title", "Automated fix for MCP endpoint issue", "--body", "This PR was automatically generated by the continuous AX Audit because the MCP endpoint failed validation.\\n\\nReason: #{inspect(reason)}\\nContext: #{inspect(context)}"])

          # Return to original branch
          System.cmd("git", ["checkout", "-"])
      rescue
         e in ErlangError ->
           Logger.error("Failed to perform PR creation commands: #{inspect(e)}")
      end
  end

  defp check_endpoint(url) do
    case Req.get(url) do
      {:ok, %{status: 200, body: body}} ->
        if is_agent_friendly?(body) do
          {:ok, url}
        else
          {:error, "Endpoint #{url} is not agent-friendly (missing semantic tags or too complex)"}
        end
      {:ok, %{status: status}} ->
        {:error, "Endpoint #{url} returned status #{status}"}
      {:error, reason} ->
        {:error, "Failed to fetch #{url}: #{inspect(reason)}"}
    end
  end

  defp is_agent_friendly?(html) do
    # Simple heuristic checks for semantic structure
    has_main = String.contains?(html, "<main")
    has_h1 = String.contains?(html, "<h1")
    # Check for excessive script usage might be tricky with simple string matching,
    # but we can check if the ratio of script tags to content is high or just ensure main content exists.

    has_main && has_h1
  end
end
